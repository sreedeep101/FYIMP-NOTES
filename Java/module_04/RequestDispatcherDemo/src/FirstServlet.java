import java.io.*;
import javax.servlet.*;
import javax.servlet.http.*;
import javax.servlet.annotation.WebServlet;

@WebServlet("/first")
public class FirstServlet extends HttpServlet {

    @Override
    protected void doGet(HttpServletRequest request,
                         HttpServletResponse response)
                         throws ServletException, IOException {

        String name = request.getParameter("name");
        String action = request.getParameter("action");

        // Pass the name to the second servlet
        request.setAttribute("username", name);

        // Create RequestDispatcher
        RequestDispatcher rd =
            request.getRequestDispatcher("/second");

        if ("forward".equals(action)) {

            // Transfer control to the second servlet
            rd.forward(request, response);

        } else if ("include".equals(action)) {

            response.setContentType("text/html;charset=UTF-8");

            PrintWriter out = response.getWriter();

            out.println("<html><body>");
            out.println("<h2>First Servlet</h2>");
            out.println("<p>Response generated by FirstServlet.</p>");

            // Include the second servlet's output
            rd.include(request, response);

            out.println("<p>FirstServlet continues after include().</p>");
            out.println("</body></html>");

        } else {

            response.sendError(
                HttpServletResponse.SC_BAD_REQUEST,
                "Invalid action. Choose forward or include."
            );
        }
    }
}
